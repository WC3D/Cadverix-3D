import { expect, test, type Page } from "@playwright/test";
import { readFile } from "node:fs/promises";
import { unzipSync, strFromU8 } from "fflate";
const state = async (page: Page) => JSON.parse(await page.locator("[data-codex-state]").textContent() ?? "{}");
test("multiple independent PCB circuits and linked instances save with mechanical geometry", async ({ page }) => {
  test.setTimeout(120000);
  const errors: string[] = []; page.on("pageerror", (error) => errors.push(error.message));
  await page.addInitScript(() => { const original = window.fetch.bind(window); window.fetch = (input, init) => /\/api\/(?:cadverix|sketchforge)-mcp/.test(String(input)) ? Promise.resolve(new Response("", { status: 404 })) : original(input, init); });
  await page.goto("/");
  await page.getByRole("button", { name: "Create new 3D design", exact: true }).click();
  await page.getByRole("button", { name: "Add shape", exact: true }).click();
  await page.getByRole("button", { name: "Box", exact: true }).click();
  await page.getByRole("tab", { name: "PCB", exact: true }).click();
  await expect(page.getByRole("button", { name: "Save combined SKF", exact: true })).toHaveCount(0);
  await expect(page.locator('.pcb-project-tools [data-tool-group="manage"]')).toHaveCount(0);
  await page.getByRole("button", { name: "Create first PCB board", exact: true }).click();
  await expect.poll(async () => (await state(page)).pcbBoards.length).toBe(1);
  await expect.poll(async () => (await state(page)).shapes.filter((shape: any) => shape.pcbInstance && shape.pcbInstance.revision !== "pending").length).toBe(1);
  await page.getByRole("button", { name: "Add Part", exact: true }).click();
  await page.locator(".part-library-item").filter({ hasText: "Resistor" }).first().click();
  await expect.poll(async () => (await state(page)).pcbBoards[0].parts).toBe(1);
  await expect.poll(async () => { const value = await state(page); return value.shapes.find((shape: any) => shape.pcbInstance)?.pcbInstance.revision === value.pcbBoards[0].revision; }).toBe(true);
  expect((await state(page)).shapes.find((shape: any) => shape.pcbInstance).height).toBeGreaterThan(1.6);
  await page.getByRole("button", { name: "Add board", exact: true }).click();
  await expect.poll(async () => (await state(page)).pcbBoards.length).toBe(2);
  await expect.poll(async () => (await state(page)).pcbBoards[1].parts).toBe(0);
  await page.getByRole("button", { name: "Manage boards / exports", exact: true }).click();
  await page.getByRole("button", { name: "Add linked instance", exact: true }).click();
  await expect.poll(async () => (await state(page)).shapeCount).toBe(4);
  await page.getByRole("button", { name: "Close board manager", exact: true }).click();
  await page.getByRole("button", { name: "Project undo", exact: true }).click();
  await expect.poll(async () => (await state(page)).shapeCount).toBe(3);
  await page.getByRole("button", { name: "Project redo", exact: true }).click();
  await expect.poll(async () => (await state(page)).shapeCount).toBe(4);
  const downloadPromise = page.waitForEvent("download");
  await page.keyboard.press("ControlOrMeta+s");
  const download = await downloadPromise, file = (await download.path())!;
  const manifest = JSON.parse(strFromU8(unzipSync(await readFile(file))["project.json"]));
  expect(manifest.formatVersion).toBe(4); expect(manifest.minimumReaderVersion).toBe(4);
  expect(manifest.states.find((entry: any) => entry.id === manifest.sceneStateId).electronics.boards).toHaveLength(2);
  await page.reload();
  await expect.poll(async () => (await state(page)).pcbBoards.length).toBe(2);
  await expect.poll(async () => (await state(page)).shapeCount).toBe(4);
  await page.getByRole("tab", { name: "PCB", exact: true }).click();
  const boards = (await state(page)).pcbBoards;
  await page.getByLabel("Active PCB board", { exact: true }).selectOption(boards[0].id);
  expect(boards[0].parts).toBe(1); expect(boards[1].parts).toBe(0);
  expect(errors).toEqual([]);
});

test("independent copies, source edits, exports and phone PCB controls remain isolated", async ({ page }) => {
  test.setTimeout(120000);
  await page.addInitScript(() => { const original = window.fetch.bind(window); window.fetch = (input, init) => /\/api\/(?:cadverix|sketchforge)-mcp/.test(String(input)) ? Promise.resolve(new Response("", { status: 404 })) : original(input, init); });
  await page.goto("/"); await page.getByRole("button", { name: "Create new 3D design", exact: true }).click();
  await page.getByRole("tab", { name: "PCB", exact: true }).click();
  await page.getByRole("button", { name: "Create first PCB board", exact: true }).click();
  await page.getByRole("button", { name: "Add Part", exact: true }).click();
  await page.locator(".part-library-item").filter({ hasText: "Resistor" }).first().click();
  await expect.poll(async () => { const value = await state(page); return value.pcbBoards[0]?.parts === 1 && value.shapes[0]?.pcbInstance?.revision === value.pcbBoards[0].revision; }).toBe(true);
  const originalId = (await state(page)).pcbBoards[0].id;
  await page.getByRole("button", { name: "Manage boards / exports", exact: true }).click();
  await page.getByLabel("PCB board name", { exact: true }).fill("Controller"); await page.getByLabel("PCB board name", { exact: true }).press("Enter");
  await page.getByRole("button", { name: "Add linked instance", exact: true }).click();
  await page.getByRole("button", { name: "Duplicate independent board", exact: true }).click();
  await expect.poll(async () => (await state(page)).pcbBoards.length).toBe(2);
  const copyId = (await state(page)).pcbBoards.find((board: any) => board.id !== originalId).id;
  await page.getByRole("button", { name: "Close board manager", exact: true }).click();
  await page.locator(".circuit-part").first().click();
  await page.getByRole("button", { name: "Delete", exact: true }).click();
  await expect.poll(async () => (await state(page)).pcbBoards.find((board: any) => board.id === copyId).parts).toBe(0);
  expect((await state(page)).pcbBoards.find((board: any) => board.id === originalId).parts).toBe(1);
  await page.getByLabel("Active PCB board", { exact: true }).selectOption(originalId);
  await page.locator(".circuit-part").first().click(); await page.getByRole("button", { name: "Delete", exact: true }).click();
  await expect.poll(async () => { const value = await state(page), board = value.pcbBoards.find((board: any) => board.id === originalId); return board.parts === 0 && value.shapes.filter((shape: any) => shape.pcbInstance?.boardId === originalId).every((shape: any) => shape.pcbInstance.revision === board.revision); }).toBe(true);
  await page.getByRole("button", { name: "Project undo", exact: true }).click();
  await expect.poll(async () => (await state(page)).pcbBoards.find((board: any) => board.id === originalId).parts).toBe(1);
  await page.getByRole("button", { name: "Manage boards / exports", exact: true }).click();
  await page.getByLabel("PCB export format", { exact: true }).selectOption("sfpcb");
  const exported = page.waitForEvent("download"); await page.getByRole("button", { name: "Export all boards", exact: true }).click();
  const files = unzipSync(await readFile((await (await exported).path())!));
  expect(Object.keys(files)).toHaveLength(2);
  const scenes = Object.values(files).map((bytes) => JSON.parse(strFromU8(bytes)).scene);
  expect(scenes.map((scene) => scene.parts.length).sort()).toEqual([0, 1]);
  await page.getByRole("button", { name: "Close board manager", exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "Manage boards / exports", exact: true }).click();
  const box = (await page.getByRole("complementary", { name: "PCB board management", exact: true }).boundingBox())!;
  expect(box.x).toBeGreaterThanOrEqual(0); expect(box.x + box.width).toBeLessThanOrEqual(390); expect(box.y + box.height).toBeLessThanOrEqual(844);
  await page.getByRole("button", { name: "Delete board and instances", exact: true }).click();
  await expect.poll(async () => (await state(page)).pcbBoards.length).toBe(1);
  expect((await state(page)).shapes.every((shape: any) => shape.pcbInstance?.boardId === copyId)).toBe(true);
  await page.getByRole("button", { name: "Add Part", exact: true }).tap();
  const library = (await page.getByRole("complementary", { name: "Component library", exact: true }).boundingBox())!;
  expect(library.x).toBeGreaterThanOrEqual(0); expect(library.x + library.width).toBeLessThanOrEqual(390); expect(library.y + library.height).toBeLessThanOrEqual(844);
  await page.getByRole("button", { name: "Close component library", exact: true }).tap();
});

