test("a late component-model response cannot reinstate an undone PCB edit", async ({ page }) => {
  let requested = false;
  let release!: () => void;
  const hold = new Promise<void>((resolve) => { release = resolve; });
  await page.route("**/assets/kicad3d/Resistor_THT.3dshapes/**", async (route) => { requested = true; await hold; await route.continue(); });
  try {
    await page.goto("/"); await page.getByRole("button", { name: "Create new 3D design", exact: true }).click();
    await page.getByRole("tab", { name: "PCB", exact: true }).click(); await page.getByRole("button", { name: "Create first PCB board", exact: true }).click();
    await expect.poll(async () => { const value = await state(page); return value.shapes[0]?.pcbInstance?.revision === value.pcbBoards[0]?.revision; }).toBe(true);
    await page.getByRole("button", { name: "Add Part", exact: true }).click(); await page.locator(".part-library-item").filter({ hasText: "Resistor" }).first().click();
    await expect.poll(() => requested).toBe(true);
    await page.getByRole("button", { name: "Project undo", exact: true }).click();
    await expect.poll(async () => (await state(page)).pcbBoards[0].parts).toBe(0);
    const finished = page.waitForEvent("requestfinished", { predicate: (request) => request.url().includes("/assets/kicad3d/Resistor_THT.3dshapes/") });
    release(); await finished;
    await page.evaluate(() => new Promise<void>((resolve) => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))));
    const value = await state(page);
    expect(value.pcbBoards[0].parts).toBe(0); expect(value.shapes[0].pcbInstance.revision).toBe(value.pcbBoards[0].revision); expect(value.shapes[0].height).toBeLessThan(2);
  } finally { release(); }
});
